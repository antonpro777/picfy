-- Pixel social features. Additive migration; existing users and messages are preserved.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS email text, ADD COLUMN IF NOT EXISTS email_verified boolean NOT NULL DEFAULT true;
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON public.users (lower(email)) WHERE email IS NOT NULL;
CREATE TABLE IF NOT EXISTS public.pixel_email_codes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 email text NOT NULL, code_hash text NOT NULL, expires_at timestamptz NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.pixel_posts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 caption text NOT NULL DEFAULT '', media_url text NOT NULL DEFAULT '',
 media_type text NOT NULL DEFAULT 'text' CHECK (media_type IN ('text','image','video','short')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pixel_posts_created_idx ON public.pixel_posts(created_at DESC);
CREATE INDEX IF NOT EXISTS pixel_posts_author_idx ON public.pixel_posts(author_id,created_at DESC);
CREATE TABLE IF NOT EXISTS public.pixel_follows (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 follower_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 following_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(follower_id,following_id), CHECK(follower_id <> following_id)
);
CREATE INDEX IF NOT EXISTS pixel_follows_following_idx ON public.pixel_follows(following_id);
CREATE TABLE IF NOT EXISTS public.pixel_likes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES public.pixel_posts(id) ON DELETE CASCADE,
 user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(post_id,user_id)
);
CREATE TABLE IF NOT EXISTS public.pixel_comments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES public.pixel_posts(id) ON DELETE CASCADE,
 user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1500),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pixel_comments_post_idx ON public.pixel_comments(post_id,created_at);
